package com.example.my_rouge_mobile.viewmodel

/**
 * Раньше размер уровня брался из размера терминала (GameWindow).
 * Теперь размер ИГРОВОГО МИРА фиксирован и не зависит от экрана телефона.
 *
 * Мир делится на сетку 3x3; в каждой ячейке (30 x 20) стоит одна комната (до 20 x 14) с зазорами
 * под коридоры. Размер ячейки должен быть не меньше самой большой комнаты + зазор:
 *   ширина  >= MAX_LENGTH (20) + ROOM_GAP_X (6) + 2 = 28  ->  MAP_WIDTH  >= 84
 *   высота  >= MAX_HEIGHT (14) + ROOM_GAP_Y (4) + 2 = 20  ->  MAP_HEIGHT >= 60
 * Если меняете размеры комнат в Room.kt, пересчитайте эти значения.
 *
 * Камера показывает только часть мира вокруг игрока (см. TILE_DP).
 */
object GameConfig {
    const val MAP_WIDTH = 150
    const val MAP_HEIGHT = 80

    /** Размер одной клетки карты на экране в dp. Меньше - видно больше карты, но мельче символы. */
    const val TILE_DP = 20f
}